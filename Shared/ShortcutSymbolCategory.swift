import Foundation

/// The icons offered for tiles: the SF Symbols behind the Shortcuts app's own glyphs,
/// grouped the way the Shortcuts icon picker groups them. Apple product symbols and
/// glyphs without a public SF Symbol are left out.
nonisolated enum ShortcutSymbolCategory: String, CaseIterable, Identifiable, Sendable {
    case objects
    case people
    case symbols

    var id: Self { self }

    var title: LocalizedStringResource {
        switch self {
        case .objects: "Objects"
        case .people: "People"
        case .symbols: "Symbols"
        }
    }

    var symbols: [String] {
        switch self {
        case .objects: Self.objectSymbols
        case .people: Self.peopleSymbols
        case .symbols: Self.symbolSymbols
        }
    }

    /// The category containing `symbol`, if any.
    static func category(containing symbol: String) -> ShortcutSymbolCategory? {
        allCases.first { $0.symbols.contains(symbol) }
    }

    /// Whether `symbol` is one of the icons DoHub offers.
    static func contains(_ symbol: String) -> Bool {
        category(containing: symbol) != nil
    }

